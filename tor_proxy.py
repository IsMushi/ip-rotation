#!/usr/bin/env python3
"""Run Tor as a local rotating SOCKS proxy for other tools.

Starts (or attaches to) Tor, writes environment files that other programs can
load, and rotates the exit IP on a timer or on demand.

    python tor_proxy.py --rotate 300

Usually started through start-proxy.ps1, which also loads the environment.

Generated files (next to this script):
    proxy.env      KEY=VALUE pairs (dotenv style)
    proxy.env.ps1  PowerShell $env: assignments
    proxy.env.cmd  cmd.exe "set" lines
    proxy.pid      daemon PID
    tor.pid        tor PID, only when this script launched Tor
"""

from __future__ import annotations

import argparse
import os
import sys
import threading
import time
from datetime import datetime
from pathlib import Path

from http_bridge import create_server as create_http_server
from tor_ip_swapper import DEFAULT_CHECK_URLS, TorIPSwapper, log

HERE = Path(__file__).resolve().parent


# --------------------------------------------------------------------------- #
# Environment files
# --------------------------------------------------------------------------- #


def _atomic_write(path: Path, text: str) -> None:
    tmp = Path(str(path) + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def write_env_files(
    base: Path,
    socks_port: int,
    control_port: int,
    trigger_file: Path,
    done_file: Path,
    http_url: str | None = None,
) -> None:
    socks_url = f"socks5h://127.0.0.1:{socks_port}"
    values = [
        ("TOR_SOCKS", f"127.0.0.1:{socks_port}"),
        ("TOR_SOCKS_URL", socks_url),
        ("TOR_CONTROL", f"127.0.0.1:{control_port}"),
        ("TOR_ROTATE_FILE", str(trigger_file)),
        ("TOR_ROTATE_DONE", str(done_file)),
    ]
    if http_url:
        values.append(("TOR_HTTP_PROXY", http_url))
    values += [
        ("ALL_PROXY", socks_url),
        ("all_proxy", socks_url),
        ("HTTP_PROXY", socks_url),
        ("HTTPS_PROXY", socks_url),
        ("http_proxy", socks_url),
        ("https_proxy", socks_url),
        ("NO_PROXY", "localhost,127.0.0.1,::1"),
        ("no_proxy", "localhost,127.0.0.1,::1"),
    ]

    header = f"# generated by tor_proxy.py at {datetime.now():%Y-%m-%d %H:%M:%S}\n"

    env_lines = [header]
    env_lines += [f"{key}={value}\n" for key, value in values]
    _atomic_write(base, "".join(env_lines))

    ps1_lines = [header]
    ps1_lines += [f"$env:{key} = '{value}'\n" for key, value in values]
    _atomic_write(Path(str(base) + ".ps1"), "".join(ps1_lines))

    cmd_lines = ["@echo off\n", "REM " + header.strip() + "\n"]
    cmd_lines += [f'set "{key}={value}"\n' for key, value in values]
    _atomic_write(Path(str(base) + ".cmd"), "".join(cmd_lines))


def remove_env_files(base: Path) -> None:
    for path in (base, Path(str(base) + ".ps1"), Path(str(base) + ".cmd")):
        try:
            path.unlink()
        except FileNotFoundError:
            pass


# --------------------------------------------------------------------------- #
# Rotation
# --------------------------------------------------------------------------- #


def mark_done(done_file: Path) -> None:
    """Signal to clients that the current rotation attempt has finished."""
    done_file.write_text(datetime.now().isoformat(timespec="seconds"), encoding="utf-8")


def rotate_once(swapper: TorIPSwapper, quiet: bool) -> None:
    started = time.monotonic()
    try:
        rotation = swapper.rotate()
    except Exception as exc:
        log(f"rotation failed: {exc}", quiet=quiet)
        return
    elapsed = time.monotonic() - started
    if rotation.changed:
        log(
            f"rotated: {rotation.old_ip} -> {rotation.new_ip} "
            f"(attempt {rotation.attempts}, {elapsed:.1f}s)",
            quiet=quiet,
        )
    else:
        log(
            f"exit IP unchanged ({rotation.new_ip}) after "
            f"{rotation.attempts} attempt(s)",
            quiet=quiet,
        )


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Keep Tor running as a rotating local SOCKS proxy.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--rotate",
        type=float,
        default=300.0,
        metavar="SECONDS",
        help="automatic rotation interval (0 = only on demand)",
    )
    parser.add_argument("--socks-port", type=int, help="Tor SOCKS port")
    parser.add_argument(
        "--http-port",
        type=int,
        default=8080,
        help="local HTTP proxy port that forwards to Tor (0 disables)",
    )
    parser.add_argument(
        "--no-http",
        action="store_true",
        help="do not start the HTTP proxy",
    )
    parser.add_argument("--control-port", type=int, help="Tor control port")
    parser.add_argument("--control-password", help="Tor control password, if any")
    parser.add_argument("--cookie-path", help="path to the control auth cookie")
    parser.add_argument("--tor-bin", help="path to the tor executable")
    parser.add_argument("--data-dir", help="data directory for a launched Tor instance")
    parser.add_argument(
        "--launch",
        action="store_true",
        help="always launch a private Tor instance instead of attaching",
    )
    parser.add_argument(
        "--no-launch",
        action="store_true",
        help="never launch Tor; fail if no running instance is found",
    )
    parser.add_argument("--settle", type=float, default=3.0, help="seconds to wait after NEWNYM")
    parser.add_argument("--attempts", type=int, default=4, help="NEWNYM attempts per rotation")
    parser.add_argument("--timeout", type=float, default=20.0, help="HTTP timeout in seconds")
    parser.add_argument(
        "--bootstrap-timeout",
        type=float,
        default=300.0,
        help="seconds to wait for a launched Tor instance to bootstrap",
    )
    parser.add_argument("--check-url", help="custom IP check URL")
    parser.add_argument(
        "--env-file",
        default=str(HERE / "proxy.env"),
        help="base path for the generated environment files",
    )
    parser.add_argument(
        "--trigger-file",
        default=str(HERE / "rotate.now"),
        help="create this file to request an immediate rotation",
    )
    parser.add_argument(
        "--done-file",
        default=str(HERE / "rotate.done"),
        help="written when a rotation finishes; clients wait for it",
    )
    parser.add_argument(
        "--stop-file",
        default=str(HERE / "stop.now"),
        help="create this file to request a clean shutdown",
    )
    parser.add_argument(
        "--pid-file", default=str(HERE / "proxy.pid"), help="daemon pid file"
    )
    parser.add_argument(
        "--tor-pid-file", default=str(HERE / "tor.pid"), help="launched tor pid file"
    )
    parser.add_argument("--quiet", action="store_true", help="suppress log lines")
    parser.add_argument("--verbose", action="store_true", help="print bootstrap output")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if args.launch and args.no_launch:
        print("error: --launch and --no-launch are mutually exclusive", file=sys.stderr)
        return 2

    check_urls = DEFAULT_CHECK_URLS
    if args.check_url:
        check_urls = (args.check_url,) + DEFAULT_CHECK_URLS

    swapper = TorIPSwapper(
        socks_port=args.socks_port,
        control_port=args.control_port,
        control_password=args.control_password,
        cookie_path=args.cookie_path,
        tor_bin=args.tor_bin,
        data_dir=args.data_dir,
        launch=True if args.launch else (False if args.no_launch else None),
        check_urls=check_urls,
        timeout=args.timeout,
        settle=args.settle,
        attempts=args.attempts,
        bootstrap_timeout=args.bootstrap_timeout,
        quiet=args.quiet,
        verbose=args.verbose,
    )

    try:
        swapper.start()
        ip, is_tor = swapper.check_ip()
    except Exception as exc:
        swapper.close()
        print(f"error: {exc}", file=sys.stderr)
        return 1

    env_base = Path(args.env_file)
    trigger_file = Path(args.trigger_file)
    done_file = Path(args.done_file)
    stop_file = Path(args.stop_file)
    pid_file = Path(args.pid_file)
    tor_pid_file = Path(args.tor_pid_file)

    http_server = None
    http_url = None
    if not args.no_http and args.http_port:
        try:
            http_server = create_http_server(
                "127.0.0.1",
                args.http_port,
                "127.0.0.1",
                swapper.socks_port,
                verbose=args.verbose,
            )
            threading.Thread(
                target=http_server.serve_forever, daemon=True, name="http-proxy"
            ).start()
            http_url = f"http://127.0.0.1:{args.http_port}"
        except OSError as exc:
            log(f"http proxy disabled: {exc}", quiet=args.quiet)

    try:
        write_env_files(
            env_base,
            swapper.socks_port,
            swapper.control_port,
            trigger_file,
            done_file,
            http_url,
        )
        pid_file.write_text(str(os.getpid()), encoding="utf-8")
        if swapper.mode == "launched" and swapper.tor_pid is not None:
            tor_pid_file.write_text(str(swapper.tor_pid), encoding="utf-8")

        log(
            f"proxy ready: {swapper.proxy_url} "
            f"(control port {swapper.control_port}, {swapper.mode}, "
            f"exit IP {ip}{' Tor' if is_tor else ''})",
            quiet=args.quiet,
        )
        if http_url:
            log(f"http proxy: {http_url}", quiet=args.quiet)
        if args.rotate > 0:
            log(f"rotating every {args.rotate:.0f}s", quiet=args.quiet)
        else:
            log("automatic rotation disabled (create rotate.now to rotate)", quiet=args.quiet)
        log(f"env file: {env_base}", quiet=args.quiet)

        next_rotation = time.monotonic() + args.rotate if args.rotate > 0 else None

        while True:
            if stop_file.exists():
                log("stop requested", quiet=args.quiet)
                break

            if trigger_file.exists():
                try:
                    trigger_file.unlink()
                except OSError:
                    pass
                rotate_once(swapper, args.quiet)
                mark_done(done_file)
                if args.rotate > 0:
                    next_rotation = time.monotonic() + args.rotate
            elif next_rotation is not None and time.monotonic() >= next_rotation:
                rotate_once(swapper, args.quiet)
                mark_done(done_file)
                next_rotation = time.monotonic() + args.rotate

            time.sleep(1)

    except KeyboardInterrupt:
        log("interrupted", quiet=args.quiet)
    finally:
        if http_server is not None:
            http_server.shutdown()
            http_server.server_close()
        remove_env_files(env_base)
        for path in (pid_file, tor_pid_file, trigger_file, done_file, stop_file):
            try:
                path.unlink()
            except FileNotFoundError:
                pass
        swapper.close()

    return 0


if __name__ == "__main__":
    sys.exit(main())
